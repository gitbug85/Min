
def strLen(s) -> int:
    return len(s)

def strEq(a, b) -> bool:
    return a == b

def strConcat(a, b) -> str:
    return a + b

def i32ToStr(x) -> str:
    return str(x)

def upper(s) -> str:
    return s.upper()

def lower(s) -> str:
    return s.lower()

def lstrip(s) -> str:
    return s.lstrip()

def strip(s) -> str:
    return s.strip()

def rstrip(s) -> str:
    return s.rstrip()